declare(strict_types=1);

/**
 * Дефолты ядра поиска на TNTSearch.
 *
 * Реквизитов подключения здесь нет и быть не может: индекс живёт в базе самого проекта, и второй
 * набор кредов означал бы второй секрет в проде и второй способ ошибиться.
 *
 * Значения `params.*` переопределяются через модуль настроек `yii2-cms-config` (опции объявлены
 * в config/options.php).
 */
return [
    'id'     => 'SearchTnt',
    'params' => [
        'iconClass' => 'bi bi-database-fill-check',

        /**
         * Стеммер индекса. `auto` — по языку приложения: русский Snowball для русского сайта,
         * английский Porter для остальных.
         *
         * Смена значения требует полной переиндексации: отсечённые основы слов лежат в индексе,
         * а не вычисляются при запросе. Собранный другим стеммером индекс молча перестаёт
         * отвечать — совпадений просто не находится.
         */
        'morphology' => 'auto',

        /**
         * Сколько совпадений забирается у движка за один запрос.
         *
         * Это заявленная граница ядра: TNTSearch не умеет фильтровать выдачу по разделам, поэтому
         * фильтр и пагинацию ядро считает по этому списку само. При большем числе совпадений на
         * один запрос выдача станет неполной на дальних страницах — это сигнал переходить на ядро
         * Manticore, а не поднимать значение до бесконечности.
         */
        'maxMatches' => 2000,

        'directories' => false,
    ],
];
